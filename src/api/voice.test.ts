import { describe, expect, it } from "vitest";
import { 말에서고르기 } from "./voice";

/*
 * 이 파일이 지키는 것 하나 — **말하지 않은 조건이 주문표에 섞이지 않는다.**
 *
 * 화면은 "당신이 고른 조건을 이렇게 썼습니다" 라고 말한다. 여기가 깨지면 그 말이
 * 거짓이 되고, 사용자는 자기가 고르지 않은 조건으로 주문하게 된다. 알아듣는 폭을
 * 넓히는 것보다 이쪽이 훨씬 중요하다.
 */

describe("말에서 고르기 — 고르기만 하고 만들지 않는다", () => {
  it("말한 것만 고른다", () => {
    const r = 말에서고르기("매운 닭강정 포장으로 두 개", "음식점");
    expect(r.고른값).toEqual({
      "맵기": ["매운맛"],
      "이용 방식": ["포장하기"],
      "수량": ["2개"],
    });
    // 말에 없던 축은 고른 값에 아예 없어야 한다. 빈 배열도 남기지 않는다.
    expect(r.못들은축).toEqual(["형태", "컵"]);
  });

  it("한 축에 두 값이 걸리면 그 축을 비운다", () => {
    // 사용자는 아직 고르는 중이다. 둘 중 하나를 우리가 고르면 그건 우리가 정한 것이다.
    const r = 말에서고르기("순한맛으로 할까 매운맛으로 할까", "음식점");
    expect(r.고른값["맵기"]).toBeUndefined();
    expect(r.못들은축).toContain("맵기");
  });

  it("무엇을 먹을지만 말하면 아무 축도 안 고른다", () => {
    const r = 말에서고르기("치킨 먹고 싶어요", "음식점");
    expect(r.고른값).toEqual({});
  });

  it("사람 수를 말해도 수량으로 옮기지 않는다", () => {
    // "혼자" 에서 1개를 만들면 그건 짐작이다. 두 명이 하나를 나눠 먹을 수도 있다.
    const r = 말에서고르기("혼자 먹을 거예요", "음식점");
    expect(r.고른값["수량"]).toBeUndefined();
  });

  it("비슷하지만 다른 말을 우리 값으로 옮기지 않는다", () => {
    // '매콤'은 순한맛일 수도 보통맛일 수도 있다. 넓히면 틀린 쪽으로 넓어진다.
    const r = 말에서고르기("적당히 매콤하게 해 주세요", "음식점");
    expect(r.고른값["맵기"]).toBeUndefined();
  });

  it("달리 부르는 말은 알아듣는다", () => {
    const r = 말에서고르기("안 맵게 뼈 없는 걸로 포장이요", "음식점");
    expect(r.고른값).toEqual({
      "맵기": ["순한맛"],
      "형태": ["순살"],
      "이용 방식": ["포장하기"],
    });
  });

  it("들은 말을 다듬지 않고 그대로 준다", () => {
    // 메뉴 이름 칸에 들어갈 값이다. 앱이 요약하거나 고쳐 쓰면 사용자가 적은 것이
    // 아닌 말이 주문표에 남는다.
    const r = 말에서고르기("  매운   닭강정  두 개 ", "음식점");
    expect(r.들은말).toBe("매운 닭강정 두 개");
  });

  it("장소를 안 골랐으면 축이 없으니 아무것도 안 고른다", () => {
    const r = 말에서고르기("매운 닭강정 포장으로 두 개", null);
    expect(r.고른값).toEqual({});
    expect(r.못들은축).toEqual([]);
  });

  it("알레르기는 말로 받지 않는다", () => {
    // 틀리면 사람이 다치는 값이라 눈으로 보고 고르게 한다(api/allergy.ts).
    // '해산물' 을 새우로 옮기는 일이 여기서 일어나면 안 된다.
    const r = 말에서고르기("새우 알레르기 있어요. 해산물은 빼 주세요", "음식점");
    expect(Object.keys(r.고른값)).not.toContain("알레르기");
    for (const 값 of Object.values(r.고른값)) expect(값).not.toContain("새우");
  });
});
