/**
 * 지금 어디에 붙어 있는지, 방금 무엇이 오갔는지 눈으로 보게 한다.
 *
 * 화면만 봐서는 목인지 실서버인지 구분할 방법이 없다. 둘 다 그럴듯한 답을
 * 돌려주기 때문이다. 그래서 실제로 나간 요청을 여기 모아 두고,
 *
 *   화면 오른쪽 아래 패널   지금 붙어 있는지, 방금 무엇이 오갔는지 (한 줄씩)
 *   주소 뒤 ?log=1         오간 것 전체를 본문까지 펼쳐 보는 화면
 *
 * 두 가지로 보여 준다. 두 번째가 "이 문장이 서버에서 온 것이다" 를 확인하는 자리다.
 *
 * 팀 백엔드 모드(npm run dev:team, npm run build:team)에서만 기록한다.
 * 기본 빌드에서는 import.meta.env.VITE_BACKEND 가 빈 문자열이라 이 모듈을
 * 부르는 쪽이 통째로 사라진다.
 */

export interface 오간것 {
  방법: string;
  경로: string;
  상태: number | "실패";
  걸린시간: number;
  시각: number;
  /** 보낸 본문. 계정 경로는 남기지 않는다 — 아래 `본문을남길까` 참고. */
  요청?: string;
  /** 받은 본문. 같은 이유로 계정 경로는 남기지 않는다. */
  응답?: string;
  /** 본문을 일부러 안 남긴 경우. 화면이 "안 남김" 과 "비어 있음" 을 구분해서 말하게 한다. */
  가림?: true;
}

/**
 * 이 경로의 본문을 남겨도 되는가.
 *
 * 계정 경로에는 비밀번호가 실린다. 이 기록은 화면 구석 패널과 ?log=1 화면에
 * 그대로 뜨므로, 남기는 순간 어깨 너머로 보인다. 남기지 않는다.
 *
 * 화이트리스트가 아니라 블랙리스트인 이유 — 새 경로가 생겼을 때 기록이 빠지는
 * 것보다 기록이 남는 쪽이 낫다. 비밀이 실릴 경로는 계정 계열뿐이고, 그건
 * 여기 적혀 있다. 새로 생기면 여기에 더한다.
 */
export const 본문을남길까 = (경로: string): boolean => !/\/api\/v1\/auth\//.test(경로);

/** ?log=1 화면이 흐름을 보여 줄 수 있을 만큼. 개발용이라 이 정도면 넉넉하다. */
const 최대 = 60;
let 기록: 오간것[] = [];
const 듣는이 = new Set<() => void>();

export const 연동기록 = {
  남기기(x: 오간것): void {
    // 오래된 것부터 버린다. 개발용이라 다 쌓아 둘 이유가 없다.
    기록 = [x, ...기록].slice(0, 최대);
    for (const f of 듣는이) f();
  },
  읽기: (): 오간것[] => 기록,
  비우기(): void {
    기록 = [];
    for (const f of 듣는이) f();
  },
  구독(f: () => void): () => void {
    듣는이.add(f);
    return () => { 듣는이.delete(f); };
  },
};

/** 팀 백엔드 모드인가. 빌드할 때 정해지므로 아닌 쪽 코드는 번들에서 빠진다. */
export const 팀백엔드모드 = import.meta.env.VITE_BACKEND === "team";
