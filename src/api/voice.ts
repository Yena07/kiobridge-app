import { DETAIL_OPTIONS } from "@/domain/catalog";
import type { PlaceType } from "@/domain/types";

/**
 * 들은 말에서 주문표에 넣을 값을 고른다.
 *
 * ── 고르기만 한다. 만들지 않는다 ────────────────────────────────────────────
 *
 * 이 파일이 지키는 규칙 하나 — **우리가 아는 값 중에서 고르기만 한다.**
 * 말에 없는 축은 비워 둔다. 비운 것은 화면이 사용자에게 묻는다.
 *
 * 짐작하지 않는 이유는 분명하다. 화면은 "당신이 고른 조건을 이렇게 썼습니다"
 * 라고 말한다. 사용자가 말하지 않은 조건이 거기 섞이면, 앱이 사용자 대신
 * 주문을 지어낸 것이 된다. "치킨 먹고 싶어" 에서 맵기를 고르지 않고,
 * "혼자 먹을 거예요" 에서 수량을 1로 만들지 않는다.
 *
 * ── 왜 여기서 고르나 ────────────────────────────────────────────────────────
 *
 * 나중에 서버가 LLM 으로 이 일을 하게 되면 이 파일은 응답을 받아 검사하는
 * 쪽으로 바뀐다. 그때도 **검사는 남는다** — 모델이 우리 목록에 없는 값을 주면
 * 버려야 하고, 그 문은 프론트에도 하나 있어야 한다.
 *
 * ── 알레르기는 여기서 안 다룬다 ─────────────────────────────────────────────
 *
 * 틀리면 사람이 다치는 값이라 말로 받지 않는다. "해산물은 좀…" 을 새우로 옮기는
 * 일이 일어나면 안 되고, 말에 안 나왔다고 '없음' 으로 확정해서도 안 된다.
 * 알레르기는 지금처럼 가입 때 눈으로 보고 고른다(api/allergy.ts).
 */

/**
 * 사람이 실제로 쓰는 말 → 우리 목록의 값.
 *
 * 목록의 값을 그대로 말하는 사람은 드물다. "포장하기" 라고 또박또박 말하지 않고
 * "포장이요" 라고 한다. 그 정도만 이어 준다 — **뜻을 넓히지는 않는다.**
 * '매콤'을 매운맛으로 옮기지 않는 이유는, 그게 순한맛일 수도 있어서다.
 */
const 다르게부르는말: Record<string, string[]> = {
  "포장하기": ["포장", "테이크아웃", "가져갈", "가져가", "싸서", "싸 주"],
  "먹고 가기": ["먹고 갈", "먹고 가", "매장", "여기서 먹"],
  "순한맛": ["순한", "안 맵", "안맵", "맵지 않"],
  "보통맛": ["보통"],
  "매운맛": ["매운", "맵게", "매워"],
  "뼈": ["뼈있", "뼈 있"],
  "순살": ["뼈없", "뼈 없", "살만"],
  "종이컵": ["종이"],
  "일반컵": ["일반"],
  "1개": ["한 개", "한개", "하나"],
  "2개": ["두 개", "두개", "둘"],
  "3개": ["세 개", "세개", "셋"],
};

/**
 * 이 말이 있으면 그 값은 **아니다.**
 *
 * 글자만 보면 부정이 긍정으로 읽힌다. "안 맵게" 안에는 '맵게' 가 들어 있고
 * "뼈 없는" 안에는 '뼈' 가 들어 있다. 그대로 두면 한 축에 두 값이 걸려 축이
 * 통째로 비는데, 하필 가장 자연스러운 말투가 그렇게 버려진다.
 *
 * 아니라는 말을 먼저 본다. 이건 뜻을 넓히는 것이 아니라 **반대로 읽는 것을
 * 막는 것**이라, 짐작하지 않는다는 규칙과 어긋나지 않는다.
 */
const 아니라는말: Record<string, string[]> = {
  "매운맛": ["안 맵", "안맵", "맵지 않", "안 매운", "덜 맵"],
  "뼈": ["뼈 없", "뼈없", "뼈 빼", "뼈 말고"],
  "먹고 가기": ["먹고 가지 않", "안 먹고"],
};

/** 이 값을 말한 것으로 볼 수 있나. 값 자체나, 달리 부르는 말이 글에 있으면 그렇다. */
const 말했나 = (글: string, 값: string): boolean =>
  !(아니라는말[값] ?? []).some((말) => 글.includes(말))
  && (글.includes(값) || (다르게부르는말[값] ?? []).some((말) => 글.includes(말)));

export interface 들은결과 {
  /** 우리 목록에서 고른 값. 화면이 쓰는 우리말 그대로다. */
  고른값: Record<string, string[]>;
  /** 말에 아예 안 나온 축. 화면이 "안 정함" 으로 보여 준다. */
  못들은축: string[];
  /**
   * 무엇을 주문하려는지. 메뉴 이름 칸에 넣을 후보다.
   *
   * 말 전체를 그대로 준다. **우리가 요약하거나 다듬지 않는다** — 사용자가 적는
   * 자리에 앱이 지어낸 말을 넣지 않는다. 화면이 그대로 보여 주고 고치게 한다.
   */
  들은말: string;
}

/**
 * 들은 말에서 이 장소의 축들을 채운다.
 *
 * 한 축에 여러 값이 걸리면 **그 축은 통째로 비운다.** "순한맛으로 할까 매운맛으로
 * 할까" 를 듣고 하나를 고르면 그건 우리가 정한 것이다. 못 고른 것으로 두고 묻는다.
 */
export const 말에서고르기 = (들은말: string, place: PlaceType): 들은결과 => {
  const 글 = 들은말.replace(/\s+/g, " ").trim();
  const 축들 = place ? DETAIL_OPTIONS[place] : [];
  const 고른값: Record<string, string[]> = {};
  const 못들은축: string[] = [];

  for (const 축 of 축들) {
    const 걸린것 = 축.choices.filter((값) => 말했나(글, 값));
    if (걸린것.length === 1) {
      고른값[축.label] = [걸린것[0]];
    } else {
      // 0개면 말 안 한 것, 2개 이상이면 무엇을 말했는지 우리가 정할 수 없는 것.
      // 둘 다 사용자에게 묻는다 — 어느 쪽이든 우리가 고르면 안 된다.
      못들은축.push(축.label);
    }
  }

  return { 고른값, 못들은축, 들은말: 글 };
};
