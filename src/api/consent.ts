/**
 * 개인정보 수집·이용 동의.
 *
 * 이 앱은 실제 이름·전화번호를 받지 않는다. 그래도 동의를 받는다 — **고른 조건도
 * 그 사람에 대한 정보**이기 때문이다. 맵기·형태·알레르기·가격 한도·안내 언어가
 * 모이면 그 사람이 무엇을 못 먹고 무엇이 불편한지가 드러난다. 이름이 없다는 것이
 * 정보가 아니라는 뜻은 아니다.
 *
 * ── 계약에 자리가 있다 ──────────────────────────────────────────────────────
 *
 *   consent.personalization : boolean
 *
 * 여태 `true` 로 박아 보내고 있었다. 그 자리에 이런 주석이 있었다 —
 * "동의 항목을 따로 묻게 되면 그 값을 여기로 넘긴다." 이제 묻는다.
 *
 * ── 이번 이용에만 남는다 ────────────────────────────────────────────────────
 *
 * 세션에 적어 새로고침을 넘기고, 창을 닫으면 사라진다(api/session.ts). 다음에
 * 이 기기를 켠 사람은 다시 동의해야 한다 — 앞사람의 동의가 다음 사람에게
 * 이어지면 그건 동의가 아니다.
 */

let 값 = false;
const 듣는이 = new Set<() => void>();

export const 개인정보동의 = {
  읽기: (): boolean => 값,
  바꾸기(동의: boolean): void {
    값 = 동의;
    for (const f of 듣는이) f();
  },
  비우기(): void {
    값 = false;
    for (const f of 듣는이) f();
  },
  /**
   * 저장해 둔 값으로 되돌린다. **듣는이에게 알리지 않는다.**
   * 화면이 첫 그림을 그리기 전에 한 번만 부른다 — a11y.ts 의 되살리기 와 같은 이유다.
   */
  되살리기(동의: unknown): void {
    // boolean 이 아니면 동의하지 않은 것으로 본다. 손댄 값으로 동의를 만들지 않는다.
    값 = 동의 === true;
  },
  구독(f: () => void): () => void {
    듣는이.add(f);
    return () => { 듣는이.delete(f); };
  },
};
