import { 접근성설정 } from "@/api/a11y";
import { EN } from "@/i18n/en";

/**
 * 화면에 나가는 말을 고른 언어로 옮긴다.
 *
 * ── 한국어를 열쇠로 쓴다 ────────────────────────────────────────────────────
 *
 * `t("담을 메뉴 확인하기")` 처럼 한국어 원문을 그대로 열쇠로 쓴다. `screen.confirm.cta`
 * 같은 이름을 새로 짓지 않는 이유가 둘 있다.
 *
 *   1. **못 옮긴 자리가 한국어로 보인다.** 이름을 열쇠로 쓰면 빠진 자리에
 *      "screen.confirm.cta" 가 뜬다. 어느 쪽이 덜 나쁜지는 분명하다.
 *   2. 코드를 읽을 때 무슨 말이 나가는지 그 자리에서 보인다. 이 저장소는
 *      화면 문구를 코드 옆에서 읽을 수 있게 두는 쪽을 계속 골라 왔다.
 *
 * ── 저장값은 안 건드린다 ────────────────────────────────────────────────────
 *
 * 주문표의 selections 는 한국어 그대로 남는다("맵기" → ["매운맛"]). 그게 서버로
 * 나가는 의미값이고(canonical.ts 가 그 한국어를 enum 으로 옮긴다), P0-1 이 요구하는
 * '사람이 읽는 값' 이기도 하다. 옮기는 것은 **보여 줄 때뿐**이다.
 */

/** 지금 고른 언어가 한국어가 아닌가. 매 호출마다 저장소를 본다 — 화면은 이미 다시 그려지고 있다. */
const 영어인가 = (): boolean => 접근성설정.읽기().language === "en-US";

/**
 * 한국어 원문을 지금 언어로. 표에 없으면 원문을 그대로 돌려준다.
 *
 * 빠진 자리가 한국어로 보이는 것은 **일부러 그렇게 둔 것**이다. 빈칸이나
 * 열쇠 이름이 뜨는 것보다 낫고, 무엇이 안 옮겨졌는지도 화면에서 바로 보인다.
 */
export const t = (ko: string): string => {
  if (!영어인가()) return ko;
  return Object.hasOwn(EN, ko) ? EN[ko] : ko;
};

/**
 * 값이 끼는 문장.
 *
 * `tf("{n}개를 지우지 못했어요", { n: 3 })` 처럼 쓴다. 언어마다 어순이 달라서
 * 문장을 토막 내 이어 붙이면 옮길 수 없는 말이 된다 — 자리표시자를 쓴다.
 */
export const tf = (ko: string, 값들: Record<string, string | number>): string => {
  let 말 = t(ko);
  for (const [k, v] of Object.entries(값들)) 말 = 말.split(`{${k}}`).join(String(v));
  return 말;
};
